# Crea una lista con 5 numeri
# - aggiungi un numero alla fine
# - sostituisci il terzo numero
# - stampa la lista finale

# Creazione della lista con 5 numeri
numeri = [10, 20, 30, 40, 50]

# Aggiunta di un numero alla fine della lista
numeri.append(60)

# Sostituzione del terzo numero
numeri[2] = 35

# Stampa della lista finale
print(numeri)